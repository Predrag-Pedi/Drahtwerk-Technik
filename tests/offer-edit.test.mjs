import test from 'node:test';
import assert from 'node:assert/strict';
import {offer,totals,offerText,validateOffer} from '../offerten/core.mjs';
import {offerHTML} from '../offerten/offer-document.mjs';
import {applyTexts,textTargets} from '../offerten/offer-edit.mjs';
function fixture(){const d=offer();d.rate=100;d.plants[0].parts[0].items=[{article:'A',name:'Originalgerät',unit:'Stk.',qty:2,price:10,minutes:6}];return d;}
test('Text editing preserves calculations and appears in formatted and plain outputs and backups',()=>{
 const d=fixture(),before=totals(d);
 applyTexts(d,{intro:'Neue Einleitung\nZusatzabsatz',closing:'Lieferung nach Absprache',p0name:'UV Garage',p0desc:'Sonderausführung',p0s0name:'Feld Nord',p0s0notes:'Zusatztext',p0s0i0:'Geänderte Beschreibung\nWeitere Angaben'});
 assert.deepEqual(totals(d),before);
 for(const candidate of [d,validateOffer(JSON.parse(JSON.stringify(d)))])for(const render of [offerHTML,offerText]){
 const text=render(candidate,'detail');assert.match(text,/Neue Einleitung/);assert.match(text,/Lieferung nach Absprache/);assert.match(text,/Sonderausführung/);assert.match(text,/Weitere Angaben/);assert.match(text,/40.00/);assert.doesNotMatch(text,/Originalgerät/);
 }
});
test('Editor exposes only text fields; unchanged autogenerated descriptions remain dynamic',()=>{
 const d=fixture();const fields=textTargets(d);
 assert.ok(!fields.some(f=>/price|qty|rate|total/.test(f.id)));
 applyTexts(d,Object.fromEntries(fields.map(f=>[f.id,f.value])));
 assert.equal(d.plants[0].offerDescription,undefined);assert.equal(d.plants[0].parts[0].items[0].offerDescription,undefined);
 const html=offerHTML(d,'detail',true);assert.match(html,/contenteditable="plaintext-only"/);assert.match(html,/data-offer-text="closing"/);
 assert.doesNotMatch(offerHTML(d,'detail'),/contenteditable/);
});
test('Edits are plain text, reject invalid fields atomically, and escape HTML',()=>{
 const d=fixture();assert.throws(()=>applyTexts(d,{intro:'Changed',price:'0'}));assert.notEqual(d.intro,'Changed');
 applyTexts(d,{p0s0i0:'<script>alert(1)</script>'});
 assert.match(offerHTML(d),/&lt;script&gt;/);assert.doesNotMatch(offerHTML(d),/<script>/);
 assert.throws(()=>applyTexts(d,{intro:'a'.repeat(50000)}));
});
